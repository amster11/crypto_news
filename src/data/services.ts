export function getService(slug: ServiceSlug): Service {
  const service = services.find((s) => s.slug === slug);
  if (!service) throw new Error(`Unknown service: ${slug}`);
  return service;
}

/** Value put into the form's "service" field for a specific offer. */
export function offerLabel(service: Service, offer: ServiceOffer) {
  return service.offers.length > 1 ? `${service.title}: ${offer.title}` : service.title;
}

/** Grouped options for the "Какая услуга интересует?" select. */
export const serviceOptionGroups = services.map((service) => ({
  label: service.title,
  options: service.offers.map((offer) => offerLabel(service, offer)),
}));

